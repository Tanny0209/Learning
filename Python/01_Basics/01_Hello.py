# LESSON: The print() function
# Purpose: Your very first program! It teaches the most basic way to
# show output on the screen using the built-in print() function.

# print() is a built-in function (Python gives it to you automatically).
# Whatever you put between the parentheses is written to the console.
# Here we pass a "string" (text wrapped in quotes) as the argument.

# When Python runs this line, it:
#   1. Reads the text inside the quotes: Hello, World!
#   2. Sends it to the console/screen so you can see it.
print("Hello, World!")
